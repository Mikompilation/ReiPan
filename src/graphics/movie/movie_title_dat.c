static int every_disp_subtitles[1] =
{
    -1,
};

// ──────────────────────────────────────────────────────────────────────
// The caption list of scene_no, null when it has none.
// FF3 0x002193a0.

MOVIE_TITLE_DAT *GetMovieTitleDat(int scene_no)
{
    int i = 0;

    do
    {
        if (movie_title_dat[i].scene_no == scene_no)
        {
            return movie_title_dat[i].dat;
        }
        i++;
    }
    while (movie_title_dat[i].dat != nullptr);
    return nullptr;
}

// Index of the caption whose window holds timer, or -1. The windows are in
// NTSC frames; in PAL both ends are scaled by 5/6.
// FF3 0x002193f8.

int GetMovieTitleDatTblPos(MOVIE_TITLE_DAT *data, int timer)
{
    if (data == nullptr)
    {
        return -1;
    }

    for (int i = 0; data[i].msg_id != -1; i++)
    {
        int start_frame = data[i].start_frame;
        int end_frame   = data[i].end_frame;

        if (GetPALMode() != 0)
        {
            start_frame = start_frame * 5 / 6;
            end_frame   = end_frame * 5 / 6;
        }
        if (start_frame <= timer && timer < end_frame)
        {
            return i;
        }
    }
    return -1;
}

// FF3 0x002194e8.

int MovieTitleIsEveryDisp(int msg_id)
{
    for (int i = 0; every_disp_subtitles[i] != -1; i++)
    {
        if (every_disp_subtitles[i] == msg_id)
        {
            return 1;
        }
    }
    return 0;
}
