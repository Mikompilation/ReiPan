// Glyph cell geometry of a font page (SetFontPat's type selects one).
struct MSG_FONT_CELL                /* 0x14 */
{
    /* 0x00 */ int w;               // cell size in texels / pixels
    /* 0x04 */ int h;
    /* 0x08 */ int off_u;           // inset of the texture rectangle in the cell
    /* 0x0c */ int off_v;
    /* 0x10 */ int cols;            // cells per row
};
static_assert(sizeof(MSG_FONT_CELL) == 0x14, "MSG_FONT_CELL is 0x14 bytes on the PS2");
static_assert(offsetof(MSG_FONT_CELL, cols) == 0x10, "MSG_FONT_CELL.cols");

// One colour label (FF2 MSG_COLOR).
