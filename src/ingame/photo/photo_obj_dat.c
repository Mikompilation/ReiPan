// Save block 29. FF3 0x0022ad18 (the file's
// __static_initialization_and_destruction_0, PhotoObjDatStaticInit, run by
// FF3 0x0022ad80, _GLOBAL__I_, .ctors 0x2e9178) clears both sets, the
// second through its constructor FF3 0x002be100; zero-initialised here.
static PHOTO_OBJ_FLG photo_obj_flg;     /* bss 0x3f7770 */

static PHOTO_OBJ_DAT *photo_obj_ene_subject;   /* sdata gp+0x2f0 */

static inline u_int PhotoObjBitTest(const PHOTO_OBJ_BITS *b, u_int no)
{
    return b->w[(int)no >> 5] & (1u << (no & 0x1f));
}

// ──────────────────────────────────────────────────────────────────────
// FF3 0x0022a930.

PHOTO_OBJ_DAT *PhotoObjGetDat(int no)
{
    return &photo_obj_dat[no];
}

// ──────────────────────────────────────────────────────────────────────
// No caller in the ROM: the photographed bit of every object flagged
// PHOTO_OBJ_FLG_RESET is cleared.
// FF3 0x0022a948.

void PhotoObjResetFlg(void)
{
    int no;

    for (no = 0; no < PHOTO_OBJ_NUM; no++)
    {
        if (PhotoObjGetDat(no)->flags & PHOTO_OBJ_FLG_RESET)
            photo_obj_flg.photographed.w[no >> 5] &= ~(1u << (no & 0x1f));
    }
}

// ──────────────────────────────────────────────────────────────────────
// Save block 29.
// FF3 0x0022a9d0.

int PhotoObjFlgSaveGet(void **addr)
{
    *addr = &photo_obj_flg;
    return sizeof(photo_obj_flg);
}

// ──────────────────────────────────────────────────────────────────────
// A photo of object no was taken (photo_dat.c 0x2282e0); a once-only
// object loses its glow.
// FF3 0x0022a9e8.

void PhotoObjSetPhotographed(int no)
{
    photo_obj_flg.photographed.w[no >> 5] |= 1u << (no & 0x1f);

    if (PhotoObjGetDat(no)->flags & PHOTO_OBJ_FLG_ONCE)
        PhotoObjSlotCut(no);
}

// ──────────────────────────────────────────────────────────────────────
// FF3 0x0022aa58.

u_int PhotoObjIsPhotographed(u_int no)
{
    return PhotoObjBitTest(&photo_obj_flg.photographed, no);
}

// ──────────────────────────────────────────────────────────────────────
// FF3 0x0022aab0.

void PhotoObjSetPhotoable(int no)
{
    photo_obj_flg.photoable.w[no >> 5] |= 1u << (no & 0x1f);
}

// ──────────────────────────────────────────────────────────────────────
// FF3 0x0022aae0.

u_int PhotoObjIsPhotoable(u_int no)
{
    return PhotoObjBitTest(&photo_obj_flg.photoable, no);
}

// ──────────────────────────────────────────────────────────────────────
// FF3 0x0022ab08.

void PhotoObjClrPhotoable(int no)
{
    photo_obj_flg.photoable.w[no >> 5] &= ~(1u << (no & 0x1f));
}

// ──────────────────────────────────────────────────────────────────────
// FF3 0x0022ab38.

PHOTO_OBJ_DAT *PhotoObjGetEneSubject(void)
{
    return photo_obj_ene_subject;
}

// ──────────────────────────────────────────────────────────────────────
// FF3 0x0022ab40.

int PhotoObjClrEneSubject(void)
{
    photo_obj_ene_subject = nullptr;
    return 0;
}

// ──────────────────────────────────────────────────────────────────────
// The object riding on enemy (kind, id) -- type 4 on kind 2, type 5 on
// kind 0 -- unless it is a once-only object already photographed. Its
// condition: 1 the enemy flags 0x1800 set; 2 the hp used up (hp <= 0 or
// hp - dmg <= 0); else none. Met: latched as the subject, 1.
// FF3 0x0022ab50.

int PhotoObjCheckEne(int kind, short id)
{
    PHOTO_OBJ_DAT *dat;
    ENE_WRK       *ew;
    int            dat_kind;
    int            no;

    for (no = 0; ; no++)
    {
        dat = PhotoObjGetDat(no);
        dat_kind = -1;
        if (dat->type == 4)
            dat_kind = 2;
        else if (dat->type == 5)
            dat_kind = 0;

        if (kind == dat_kind && dat->ene_id == id)
            break;

        if (no + 1 >= PHOTO_OBJ_NUM)
            return 0;
    }

    if ((dat->flags & PHOTO_OBJ_FLG_ONCE) && PhotoObjIsPhotographed((u_int)no) != 0)
        return 0;

    ew = EneGetWrk((u_char)kind, id);
    if (dat->ene_cond == 1)
    {
        if ((ew->flags & 0x1800) == 0)
            return 0;
    }
    else if (dat->ene_cond == 2)
    {
        if (ew->hp > 0 && ew->hp - ew->dmg > 0)
            return 0;
    }

    photo_obj_ene_subject = dat;
    return 1;
}

// ──────────────────────────────────────────────────────────────────────
// PhotoDatInit.
// FF3 0x0022aca0.

void PhotoObjDatInit(void)
{
    memset(&photo_obj_ene_subject, 0, sizeof(photo_obj_ene_subject));
    memset(&photo_obj_flg, 0, sizeof(photo_obj_flg));
}
